	 public function getSales($date,$warehouse_id = NULL, $year = NULL, $month = NULL)
    {
        $myQuery = "SELECT  
        SUM( COALESCE( si.subtotal, 0 ) ) AS sales,
        SUM( COALESCE( (p.cost*si.quantity), 0 ) ) AS cost,
        SUM( COALESCE( si.discount, 0 ) ) AS discount
        
            FROM " . $this->db->dbprefix('sale_items') . " si  left join ".$this->db->dbprefix('sales')." s on s.id=si.sale_id left join "
            .$this->db->dbprefix('products')." p on p.id=si.product_id where 1=1 ";

        {
          $myQuery .= " and  ( s.date >= '".$date." 00:00:00' and s.date <= '".$date." 23:59:59' )";
        }
         elseif ($month) {
            $this->load->helper('date');
            $last_day = days_in_month($month, $year);
         //   $this->db->where('s.date >=', $year.'-'.$month.'-01 00:00:00');
          //  $this->db->where('s.date <=', $year.'-'.$month.'-'.$last_day.' 23:59:59');

            $sd=$year.'-'.$month.'-01 00:00:00';
            $ed=$year.'-'.$month.'-'.$last_day.' 23:59:59';

            $myQuery .= " and  ( s.date >= '".$sd." 00:00:00' and s.date <= '".$ed." 23:59:59' )";
        }
        
        $q = $this->db->query($myQuery, false);

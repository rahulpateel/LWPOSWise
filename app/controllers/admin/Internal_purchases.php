            if (!empty($_POST['val'])) {
                if ($this->input->post('form_action') == 'delete') {

                    $this->sma->checkPermissions('delete');
                    foreach ($_POST['val'] as $id) {
                        $this->internal_purchases_model->deletePurchase($id);
                    }
                    $this->session->set_flashdata('message', $this->lang->line("internal_purchases_deleted"));
                    redirect($_SERVER["HTTP_REFERER"]);

